const ZWJ = 0x200d;
const VS16 = 0xfe0f;

function codePointsOf(emoji: string): number[] {
  const points: number[] = [];

  for (const char of emoji) points.push(char.codePointAt(0) ?? 0);

  return points;
}

// Twemoji's file naming: U+FE0F is dropped unless the sequence is a ZWJ sequence.
function fileKey(emoji: string): string {
  const points = codePointsOf(emoji);
  const kept = points.includes(ZWJ) ? points : points.filter((point) => point !== VS16);

  return kept.map((point) => point.toString(16)).join('-');
}

function svgDirFromArgs(): string {
  const index = process.argv.indexOf('--svg-dir');

  if (index !== -1) return resolve(process.argv[index + 1]);

  const work = mkdtempSync(join(tmpdir(), 'leclap-emoji-'));
  const tarball = execFileSync('npm', ['pack', SVG_PACKAGE, '--silent'], { cwd: work, encoding: 'utf8' }).trim();

  execFileSync('tar', ['xzf', tarball], { cwd: work });

  return join(work, 'package');
}

function svgFor(svgDir: string, key: string): string | null {
  const candidates = [key, key.replace(/-fe0f/g, '')];
  const found = candidates.map((name) => join(svgDir, `${name}.svg`)).find((path) => existsSync(path));

  return found ? readFileSync(found, 'utf8') : null;
}

const svgDir = svgDirFromArgs();

mkdirSync(outDir, { recursive: true });

for (const file of readdirSync(outDir).filter((name) => name.endsWith('.png'))) rmSync(join(outDir, file));

const keys = [...new Set(EMOJI.map(fileKey))].sort();
const written: string[] = [];

for (const key of keys) {
  const svg = svgFor(svgDir, key);

  if (!svg) {
    console.warn(`  missing ${key}.svg — skipped`);
    continue;
  }

  const png = new Resvg(svg, { fitTo: { mode: 'width', value: SIZE } }).render().asPng();

  writeFileSync(join(outDir, `${key}.png`), png);
  written.push(key);
}

const manifest = `// GENERATED by scripts/gen-emoji.ts — do not edit.
// The colour emoji bundled as ${SIZE}px PNGs under @leclap/creative-kit/src/library/emoji/ (Twemoji, CC-BY 4.0),
// keyed by code-point sequence: lowercase hex joined by '-', U+FE0F dropped outside ZWJ sequences.

export const EMOJI_ASSET_SIZE = ${SIZE};

export const EMOJI_ASSET_KEYS: readonly string[] = [
${written.map((key) => `  '${key}',`).join('\n')}
];
`;

writeFileSync(manifestPath, manifest);
console.log(`✓ ${written.length} emoji → ${outDir}`);
