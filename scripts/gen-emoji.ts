// Rasterize the bundled colour-emoji subset that text lowering composites as image overlays (drawtext
// draws monochrome outlines only, so colour emoji are drawn as PNGs next to the text).
//
// Source: the Twemoji graphics (CC-BY 4.0, https://github.com/jdecked/twemoji), read from the
// `@twemoji/svg` npm package so the script works through an npm registry proxy. Each emoji is
// rendered to a 72x72 PNG named by its code-point sequence (lowercase hex joined by '-', the variation
// selector U+FE0F dropped outside ZWJ sequences) into packages/leclap-creative-kit/src/library/emoji/,
// and the engine's manifest (src/core/emoji-manifest.generated.ts) is rewritten to list them.
//
// Run: `pnpm gen:emoji` (or `node scripts/gen-emoji.ts --svg-dir <dir with the .svg files>`).
